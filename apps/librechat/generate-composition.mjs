// Use the already pinned build tools; no install and no upstream edits.
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../../', import.meta.url));
const require = createRequire(resolve(root, '.local/upstream/LibreChat-f4154b6/client/package.json'));
const Ajv = require('ajv');
const standalone = require('ajv/dist/standalone').default;
const v2 = process.argv.includes('--v2');
const name = v2 ? 'LearningCompositionV2' : 'LearningComposition';
const prefix = v2 ? 'composition-v2' : 'composition';
const schema = JSON.parse(execFileSync('uv', [
  'run', '--frozen', '--directory', resolve(root, 'backend'),
  'python', '-m', 'leornian.entrypoints.export_composition', '--version', v2 ? '2' : '1',
], { cwd: root, encoding: 'utf8' }));
const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
ajv.addFormat('uuid', /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i);
const validate = ajv.compile(schema);
// Keep the validator CSP-safe and standalone, including Unicode string lengths.
const module = '// Generated by node apps/librechat/generate-composition.mjs. Do not edit.\n'
  + standalone(ajv, validate).replaceAll('require("ajv/dist/runtime/ucs2length").default',
    '(s => [...s].length)');

// Reuse the project's existing OpenAPI type generator for type-only definitions.
const contractRequire = createRequire(resolve(root, 'packages/api-contracts/package.json'));
const { default: openapiTS, astToString } = contractRequire('openapi-typescript');
const relocate = (value) => {
  if (typeof value === 'string') return value.replace('#/$defs/', '#/components/schemas/');
  if (Array.isArray(value)) return value.map(relocate);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value)
    .filter(([key]) => key !== '$defs')
    .map(([key, child]) => [key, relocate(child)]));
  return value;
};
const types = astToString(await openapiTS({
  openapi: '3.1.0', info: { title: 'Learning composition (not an HTTP API)', version: '1' }, paths: {},
  components: { schemas: Object.fromEntries(Object.entries({ ...schema.$defs, [name]: schema })
    .map(([typeName, value]) => [typeName, relocate(value)])) },
}));
const outputs = [
  [`${prefix}-schema.json`, JSON.stringify(schema, null, 2) + '\n'],
  [`${prefix}-validator.generated.mjs`, module + '\n'],
  [`${prefix}-types.generated.ts`, types],
];
if (v2) outputs.push(['composition-directory.generated.json', JSON.stringify(JSON.parse(execFileSync('uv', [
  'run', '--frozen', '--directory', resolve(root, 'backend'),
  'python', '-m', 'leornian.entrypoints.export_composition', '--directory',
], { cwd: root, encoding: 'utf8' })), null, 2) + '\n']);
for (const [name, content] of outputs) {
  const path = new URL(name, import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`Stale generated contract: ${name}`);
  } else await writeFile(path, content);
}
console.log(process.argv.includes('--check') ? 'Composition exports are current.' : 'Composition schema, validator and types generated.');
